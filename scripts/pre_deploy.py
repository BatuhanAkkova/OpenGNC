#!/usr/bin/env python3
"""OpenGNC Pre-Commit & Pre-Deployment Verification Suite.

This script executes all pre-flight checks required before committing code
or triggering GitHub Actions CI/CD deployments and PyPI releases:
  1. Code formatting check (ruff format)
  2. Static linting & imports (ruff check)
  3. Static typing (mypy src)
  4. Test suite execution (pytest)
  5. C++ build & ctest execution (optional/auto-detected)
  6. Package distribution build (python -m build)
  7. Package metadata & README rendering validation (twine check --strict)
  8. Sphinx documentation build (optional/verification)

Usage:
  python scripts/pre_deploy.py                  # Standard pre-flight check
  python scripts/pre_deploy.py --all            # Complete check (including docs & packaging)
  python scripts/pre_deploy.py --fix            # Auto-format and auto-fix before checking
  python scripts/pre_deploy.py --install-hook   # Install as Git pre-push hook
"""

from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
import time
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent


def print_header(title: str) -> None:
    sep = "=" * 70
    print(f"\n{sep}\n>>> {title}\n{sep}")


def run_step(name: str, cmd: list[str], cwd: Path | None = None) -> bool:
    print_header(f"Running: {name}")
    print(f"Command: {' '.join(cmd)}\n")
    t0 = time.perf_counter()
    res = subprocess.run(cmd, cwd=cwd or REPO_ROOT)
    elapsed = time.perf_counter() - t0
    if res.returncode == 0:
        print(f"\n[PASS] {name} completed successfully in {elapsed:.2f}s")
        return True
    else:
        print(f"\n[FAIL] {name} failed with exit code {res.returncode} in {elapsed:.2f}s")
        return False


def install_git_hook(hook_type: str = "pre-push") -> int:
    hooks_dir = REPO_ROOT / ".git" / "hooks"
    if not hooks_dir.exists():
        print(f"Error: Git hooks directory not found at {hooks_dir}")
        return 1

    hook_file = hooks_dir / hook_type
    python_cmd = sys.executable

    script_content = f"""#!/bin/sh
# Auto-generated by scripts/pre_deploy.py
echo "Running OpenGNC pre-deployment verification..."
"{python_cmd}" scripts/pre_deploy.py --all
EXIT_CODE=$?
if [ $EXIT_CODE -ne 0 ]; then
    echo "OpenGNC pre-deployment checks failed. Aborting push."
    exit $EXIT_CODE
fi
exit 0
"""
    hook_file.write_text(script_content, encoding="utf-8")
    try:
        hook_file.chmod(0o755)
    except Exception:
        pass
    print(f"[OK] Installed Git hook at {hook_file}")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description="OpenGNC Pre-Commit and Pre-Deployment Validator")
    parser.add_argument(
        "--all", action="store_true", help="Run full suite including packaging, C++, and docs"
    )
    parser.add_argument(
        "--fix", action="store_true", help="Automatically format and fix issues where possible"
    )
    parser.add_argument("--skip-cpp", action="store_true", help="Skip C++ test builds")
    parser.add_argument("--skip-tests", action="store_true", help="Skip pytest execution")
    parser.add_argument(
        "--skip-build", action="store_true", help="Skip wheel/sdist packaging build"
    )
    parser.add_argument("--skip-docs", action="store_true", help="Skip documentation build")
    parser.add_argument("--install-hook", action="store_true", help="Install Git pre-push hook")

    args = parser.parse_args()

    if args.install_hook:
        return install_git_hook()

    failures: list[str] = []

    # Step 0: Auto-fix if requested
    if args.fix:
        print_header("Applying Automatic Formatting & Ruff Fixes")
        subprocess.run([sys.executable, "-m", "ruff", "format", "src", "tests"], cwd=REPO_ROOT)
        subprocess.run([sys.executable, "-m", "ruff", "check", "--fix", "src"], cwd=REPO_ROOT)

    # Step 1: Ruff Formatting Check
    if not run_step(
        "Ruff Code Format Check",
        [sys.executable, "-m", "ruff", "format", "--check", "src", "tests"],
    ):
        failures.append("Ruff Format Check (run `python -m ruff format src tests` to fix)")

    # Step 2: Ruff Lint Check
    if not run_step("Ruff Linting", [sys.executable, "-m", "ruff", "check", "src"]):
        failures.append("Ruff Linting (run `python -m ruff check --fix src` to auto-fix)")

    # Step 3: Mypy Typecheck
    if not run_step("Mypy Type Checking", [sys.executable, "-m", "mypy", "src"]):
        failures.append("Mypy Type Checking")

    # Step 4: Pytest Suite
    if not args.skip_tests:
        if not run_step("Pytest Suite", [sys.executable, "-m", "pytest", "tests"]):
            failures.append("Pytest Suite")

    # Step 5: C++ Build & Tests (if cmake available and not skipped)
    has_cmake = shutil.which("cmake") is not None
    if has_cmake and not args.skip_cpp and (args.all or (REPO_ROOT / "cpp").exists()):
        build_dir = REPO_ROOT / "build_pre_flight"
        cfg_cmd = [
            "cmake",
            "-B",
            str(build_dir),
            "-S",
            str(REPO_ROOT),
            "-DCMAKE_BUILD_TYPE=Release",
            "-DBUILD_TESTING=ON",
        ]
        bld_cmd = [
            "cmake",
            "--build",
            str(build_dir),
            "--config",
            "Release",
            "--target",
            "test_runner",
        ]
        tst_cmd = ["ctest", "--test-dir", str(build_dir), "-C", "Release", "--output-on-failure"]

        if not run_step("C++ CMake Configure", cfg_cmd):
            failures.append("C++ CMake Configure")
        elif not run_step("C++ Build test_runner", bld_cmd):
            failures.append("C++ Build test_runner")
        elif not run_step("C++ CTest Runner", tst_cmd):
            failures.append("C++ CTest Runner")

    # Step 6: Build Package (sdist + wheel)
    if args.all and not args.skip_build:
        dist_dir = REPO_ROOT / "dist"
        if dist_dir.exists():
            for f in dist_dir.glob("*"):
                try:
                    f.unlink()
                except Exception:
                    pass

        if not run_step("Package Build (sdist + wheel)", [sys.executable, "-m", "build"]):
            failures.append("Package Build (build)")
        else:
            # Step 7: Twine check
            if not run_step(
                "Twine Strict Metadata Validation",
                [sys.executable, "-m", "twine", "check", "--strict", "dist/*"],
            ):
                failures.append("Twine Metadata Validation")

    # Step 8: Docs Build
    if args.all and not args.skip_docs:
        docs_script = REPO_ROOT / "docs" / "build_docs.py"
        if docs_script.exists():
            if not run_step("Documentation Build", [sys.executable, str(docs_script)]):
                failures.append("Documentation Build")

    # Summary
    print("\n" + "=" * 70)
    if not failures:
        print("[SUCCESS] All pre-commit and pre-deployment checks PASSED!")
        print("Your repository is clean, airtight, and ready for deployment.")
        print("=" * 70)
        return 0
    else:
        print("[FAILURE] The following checks failed:")
        for fail in failures:
            print(f"  - {fail}")
        print("\nPlease fix the issues above before pushing or releasing.")
        print("=" * 70)
        return 1


if __name__ == "__main__":
    sys.exit(main())
